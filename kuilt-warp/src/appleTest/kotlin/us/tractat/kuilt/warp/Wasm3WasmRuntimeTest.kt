package us.tractat.kuilt.warp

import kotlinx.coroutines.test.runTest
import us.tractat.kuilt.test.assertAll
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertFailsWith

/**
 * Integration tests for [Wasm3WasmRuntime]: happy-path execution plus the load-time sandbox
 * guards, mirroring [ChicoryWasmRuntimeTest] over the native wasm3 cinterop.
 *
 * Happy path: `reverse.wasm` exports the warp linear-memory ABI (`memory`, `warp_alloc`,
 * `warp_run`) and reverses its input bytes — proving args marshal into wasm3 linear memory,
 * `warp_run` executes, and the packed result reads back.
 *
 * Load-guard tests verify that [Wasm3WasmRuntime.load] rejects capability-violating modules
 * with [WasmLoadException] before any execution occurs: a declared import, an oversize memory
 * ceiling (declared max or initial), memory declared with no explicit max (a memory bomb),
 * malformed bytes, a missing `warp_alloc`/`warp_run` ABI export, and a module that exports the
 * ABI but no linear memory. A run-guard test proves wasm3 enforces a declared max at grow time.
 *
 * Run-guard: a trapping kernel surfaces as [WasmExecutionException]. wasm3 has no safe
 * cross-thread abort surface, so a CPU-bomb execution-timeout bound is deferred (see the
 * [Wasm3WasmRuntime] KDoc); only the load-time guards are asserted here.
 *
 * wasm fixtures are embedded as byte literals — Kotlin/Native has no classpath resource loading,
 * so the same kernels the JVM test reads from `src/jvmTest/resources` are inlined verbatim here.
 *
 * @see Wasm3RuntimeDispatchTest
 */
class Wasm3WasmRuntimeTest {

    private val runtime = Wasm3WasmRuntime()

    // --- Happy-path tests — guards must not over-reject reverse.wasm ---

    @Test
    fun fourBytesReverse() = runTest {
        val op = runtime.load(REVERSE_WASM)
        assertContentEquals(byteArrayOf(4, 3, 2, 1), op.invoke(byteArrayOf(1, 2, 3, 4)))
    }

    @Test
    fun emptyInputReturnsEmpty() = runTest {
        val op = runtime.load(REVERSE_WASM)
        assertContentEquals(byteArrayOf(), op.invoke(byteArrayOf()))
    }

    @Test
    fun asciiPayloadRoundTripsReversed() = runTest {
        val op = runtime.load(REVERSE_WASM)
        val input = "Hello, warp!".encodeToByteArray()
        val expected = input.reversedArray()
        val first = op.invoke(input)
        val second = op.invoke(input)
        assertAll(
            { assertContentEquals(expected, first) },
            { assertContentEquals(expected, second, "second invoke reuses the same instance") },
        )
    }

    // --- Load-guard tests ---

    @Test
    fun loadRejectsModuleWithImports() {
        assertFailsWith<WasmLoadException> { runtime.load(IMPORTS_WASM) }
    }

    @Test
    fun loadRejectsModuleWithOversizeMemory() {
        assertFailsWith<WasmLoadException> { runtime.load(BIGMEM_WASM) }
    }

    @Test
    fun loadRejectsModuleWithOversizeInitialMemory() {
        assertFailsWith<WasmLoadException> { runtime.load(LARGEINIT_WASM) }
    }

    @Test
    fun loadRejectsMalformedBytes() {
        assertFailsWith<WasmLoadException> { runtime.load(byteArrayOf(0x00, 0x61, 0x73, 0x6d, 0x09)) }
    }

    @Test
    fun loadRejectsModuleMissingAbiExports() {
        assertFailsWith<WasmLoadException> { runtime.load(NOABI_WASM) }
    }

    @Test
    fun loadRejectsModuleMissingMemoryExport() {
        assertFailsWith<WasmLoadException> { runtime.load(NOMEMORY_WASM) }
    }

    /**
     * A module declaring memory with NO explicit max passes a declared-max-only check, but wasm3
     * defaults the runtime ceiling to 65536 pages (~4 GiB) for a no-max module, so its kernel can
     * `memory.grow` unbounded — a memory-exhaustion DoS (the native counterpart of #952/#963).
     * [Wasm3WasmRuntime.load] must reject it so every loaded module carries a bounded, enforced max.
     */
    @Test
    fun loadRejectsModuleDeclaringMemoryWithNoMax() {
        assertFailsWith<WasmLoadException> { runtime.load(NOMAX_WASM) }
    }

    // --- Run-guard tests ---

    @Test
    fun trapSurfacesAsExecutionException() = runTest {
        assertFailsWith<WasmExecutionException> { runtime.load(TRAP_WASM).invoke(ByteArray(0)) }
    }

    /**
     * Evidence that reject-no-max is sufficient: wasm3 enforces a module's *declared* max at grow
     * time. [GROWMAX_WASM] declares memory `(1, max 1)` and its `warp_run` calls `memory.grow(1)`
     * (which would require 2 pages); wasm3's `ResizeMemory` denies the grow, `memory.grow` returns
     * `-1`, and the kernel converts that into `unreachable` → [WasmExecutionException]. If wasm3 did
     * NOT honor the declared max, the grow would succeed (return prev pages, not `-1`), no trap would
     * fire, and this would fail — the signal to re-plan (reject-no-max alone would be insufficient).
     */
    @Test
    fun loadEnforcesDeclaredMaxOnGrow() = runTest {
        assertFailsWith<WasmExecutionException> { runtime.load(GROWMAX_WASM).invoke(ByteArray(0)) }
    }

    /**
     * A guest whose `warp_run` returns a packed result pointer with bit 31 set (`resPtr >= 2^31`)
     * must be rejected as a bounded [WasmExecutionException], not read out of bounds. With signed
     * `Int` decoding the pointer wraps negative, slips past a naive `end > size` guard, and indexes
     * host memory below the linear-memory base — a sandbox-escape OOB read.
     */
    @Test
    fun runResultPointerWithHighBitSetIsBounded() = runTest {
        assertFailsWith<WasmExecutionException> { runtime.load(OOB_RESPTR_WASM).invoke(ByteArray(0)) }
    }

    /**
     * A guest whose `warp_run` returns a packed result length with bit 31 set (`resLen >= 2^31`)
     * must surface a [WasmExecutionException]. With signed `Int` decoding the length wraps negative
     * and hits `ByteArray(len)` → a raw `NegativeArraySizeException` that escapes the sealed
     * [WasmException] hierarchy and the executor's terminal-error handling (anti-entropy DoS).
     */
    @Test
    fun runResultLengthWithHighBitSetIsBounded() = runTest {
        assertFailsWith<WasmExecutionException> { runtime.load(BAD_RESLEN_WASM).invoke(ByteArray(0)) }
    }

    /**
     * A guest whose `warp_alloc` returns a pointer with bit 31 set must be rejected before the host
     * writes the marshalled args — otherwise the signed-`Int` pointer wraps negative and
     * [Wasm3WasmRuntime] writes args below the linear-memory base: an OOB host-memory *write*.
     */
    @Test
    fun allocPointerWithHighBitSetIsBounded() = runTest {
        assertFailsWith<WasmExecutionException> {
            runtime.load(OOB_ALLOC_WASM).invoke(byteArrayOf(1, 2, 3, 4))
        }
    }
}

