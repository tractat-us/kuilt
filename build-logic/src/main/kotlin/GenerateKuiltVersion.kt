import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes `GeneratedVersion.kt`, the `commonMain` source holding the version this build publishes as
 * `internal fun generatedVersion()`, so a consumer that records which kuilt wrote something
 * reads it instead of hand-copying a string that drifts on every upgrade (#3323).
 *
 * The public face is hand-written: `public object KuiltVersion { public val VERSION = generatedVersion() }`
 * in [CARRIER]'s `src/commonMain`, in [PACKAGE]. Only the string is generated, for two reasons.
 * The module then has declared source of its own, so `forbidSourcelessKmpTarget`, which ignores
 * anything under `build/` (#2374), sees a real target rather than a source-less one. And the KDoc
 * and its `@sample` sit in `src/`, where `verifySampleLinks` and Dokka read them directly. The
 * literal is returned from a function, never held in a `const` (#3464). Kotlin's JVM classpath
 * snapshot records `const` values, `internal` ones included, so a `const` here gave every
 * JVM/Android/metadata compile that sees [CARRIER] a new cache key on every snapshot run, whose
 * version differs by run number. A function body is not part of that snapshot. A klib still
 * carries the body as IR, so on native and wasm the literal changes [CARRIER]'s klib on every run
 * whatever its form: only a module that does not depend on [CARRIER] is spared that recompile.
 *
 * One module carries it, so there is one class with one fully qualified name, never a split
 * package. No other kuilt module depends on it: a consumer that wants the value declares
 * `us.tractat.kuilt:kuilt-base`, versionless under the BOM.
 *
 * **Warning:** every snapshot stamps a new version into [CARRIER], so on native and wasm a module
 * that adds a dependency on it recompiles on every snapshot, and so does everything above it (#3464).
 *
 * [libraryVersion] is an `@Input`, so a `-Pversion=…` override reruns this task and the compile
 * tasks behind it rather than serving the previous version's source. The value is checked against
 * [VERSION_SHAPE] before it is written: it lands inside a Kotlin string literal, and a version
 * carrying a quote, a backslash or a `$` would otherwise compile into something else, or not at all.
 */
abstract class GenerateKuiltVersion : DefaultTask() {

    @get:Input
    abstract val libraryVersion: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val version = libraryVersion.get()
        require(VERSION_SHAPE.matches(version)) {
            "Refusing to generate KuiltVersion for version '$version': it must match $VERSION_SHAPE " +
                "to be written into a Kotlin string literal unescaped."
        }
        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        val file = root.resolve(PACKAGE.replace('.', '/')).resolve("GeneratedVersion.kt")
        file.parentFile.mkdirs()
        file.writeText(source(version))
    }

    companion object {
        /** Maven/semver-shaped: what `<line>.0-dev`, `<line>.0-dev.<run>` and a tag's `x.y.z` all are. */
        val VERSION_SHAPE: Regex = Regex("""[A-Za-z0-9][A-Za-z0-9._+-]*""")

        /** The one module that carries `KuiltVersion`. The plugin refuses to apply anywhere else. */
        const val CARRIER: String = ":kuilt-base"

        /** The package of the hand-written `KuiltVersion` and of the generated constant beside it. */
        const val PACKAGE: String = "us.tractat.kuilt"

        fun source(version: String): String = """
            |// Generated by the kuilt.version-constant convention plugin. Do not edit.
            |package $PACKAGE
            |
            |/** The version this build publishes. Read it through [KuiltVersion.VERSION]; see there for why that is not a `const`. */
            |internal fun generatedVersion(): String = "$version"
            |""".trimMargin()
    }
}
