import org.gradle.api.Action
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.Task
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Writes the Karma **line reporter** into each module's `karma.config.d` directory, so a wasm
 * browser test run reaches Gradle one line per message instead of one line per run (#3605).
 *
 * ## The defect it fixes
 *
 * Kotlin's `karma-kotlin-reporter` (in `kotlin-web-helpers`) writes every TeamCity service
 * message, and every line a test logged, with `this.write(line)` and **no newline**. Karma's own
 * `write` adds none either, so a whole run of tests leaves the Karma process as a single line of
 * stdout. KGP's `TCServiceMessageOutputStreamHandler` buffers up to a newline and caps that buffer
 * at 1 MB (`MESSAGE_LIMIT_BYTES`). Past the cap, outside a running test, it logs the buffer, throws
 * it away and dispatches a `testFailed name='overflow-message'` that fails with "no running test",
 * and the task still exits 0. `:kuilt-session` hit it at 26 of 543 results (#3605), and
 * `:kuilt-otel` before it (#2185). The ceiling was never per message: it was per **run**, so every
 * module's ceiling fell as its suite grew.
 *
 * The wrapper registers a reporter that delegates to Kotlin's own and appends the missing newline
 * to each write. Each service message is then one line, as the TeamCity format expects, and the
 * 1 MB cap applies to one message. A single logged line over 1 MB holds no `##teamcity[` and is
 * passed on as plain output in 1 MB pieces, and an over-long message inside a test fails that
 * test, so neither case loses a result in silence.
 *
 * `kotlin.ignore.tcsm.overflow=true` is not a substitute. It only skips the failure: the handler
 * still cuts the line every 1 MB, so whichever service message straddles a cut is parsed as plain
 * text and lost. Which one that is depends on byte counts, so a `testFinished` can go without
 * anything saying so.
 *
 * ## The count it reports
 *
 * The wrapper also counts the results it hands on (passed, failed and skipped) and writes the
 * total to [COUNT_FILE_NAME] in the Karma working directory. [VerifyKarmaResultCount] compares it
 * with the `<testcase>` rows Gradle wrote and fails the task on a shortfall. That turns any silent
 * drop between Karma and Gradle into a red `wasmJsBrowserTest` on every machine, the local build
 * included. It does not depend on knowing the cause, so it also covers whatever drops results
 * next.
 *
 * ## It refuses to fail open
 *
 * If Kotlin renames the reporter or changes its export, the wrapper throws at Karma config time.
 * A wrapper that silently stops wrapping would bring back the one-line run with nothing to say so.
 * The count file is written only by the wrapper, so a missing file after a run also fails the
 * task. Either way, a disarmed guard shows up as a red build.
 */
abstract class GenerateKarmaLineReporter : DefaultTask() {

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val file = outputFile.get().asFile
        file.parentFile.mkdirs()
        file.writeText(CONTENT)
    }

    companion object {
        /** Written by the wrapper into the Karma working directory: the number of results it reported. */
        const val COUNT_FILE_NAME: String = "kuilt-karma-reported-results.txt"

        /**
         * Content of the generated `line-reporter.js`, appended by Kotlin's Karma integration into
         * the body of `karma.conf.js`, where `config`, `require` and `process` are in scope and
         * `NODE_PATH` resolves `kotlin-web-helpers`.
         */
        val CONTENT: String = """
            |// Generated by kuilt.kmp-library convention plugin — do not edit by hand.
            |//
            |// Line reporter (#3605): Kotlin's karma-kotlin-reporter writes each service message
            |// with no trailing newline, so a whole run reaches Gradle as ONE line and KGP drops
            |// everything past its 1 MB per-line cap while the task exits 0. This delegates to that
            |// reporter, ends every write with a newline, and records how many results it reported
            |// so the Gradle side can fail on a shortfall.
            |(function () {
            |    var original = 'karma-kotlin-reporter';
            |    var replacement = 'kuilt-line-reporter';
            |    var reporters = config.reporters || [];
            |    if (reporters.indexOf(original) < 0) {
            |        throw new Error('kuilt line reporter (#3605): expected Kotlin\'s ' + original +
            |            ' in the Karma reporters, found ' + JSON.stringify(reporters) +
            |            '. Kotlin changed its Karma integration; re-check whether it still writes ' +
            |            'service messages without a newline, and update GenerateKarmaLineReporter.');
            |    }
            |    var plugin = require('kotlin-web-helpers/dist/karma-kotlin-reporter.js')['reporter:' + original];
            |    if (!plugin || typeof plugin[1] !== 'function') {
            |        throw new Error('kuilt line reporter (#3605): kotlin-web-helpers no longer exports ' +
            |            'reporter:' + original + ' as a constructor. Update GenerateKarmaLineReporter.');
            |    }
            |    var KotlinReporter = plugin[1];
            |    var countFile = require('path').join(process.cwd(), '$COUNT_FILE_NAME');
            |
            |    function LineReporter(baseReporterDecorator, config, emitter) {
            |        KotlinReporter.call(this, baseReporterDecorator, config, emitter);
            |        var write = this.write;
            |        this.write = function () {
            |            write.apply(this, arguments);
            |            var last = arguments[arguments.length - 1];
            |            if (!(arguments.length === 1 && typeof last === 'string' && last.slice(-1) === '\n')) {
            |                write.call(this, '\n');
            |            }
            |        };
            |        var reported = 0;
            |        var self = this;
            |        ['specSuccess', 'specFailure', 'specSkipped'].forEach(function (name) {
            |            var handler = self[name];
            |            self[name] = function () {
            |                reported++;
            |                return handler.apply(this, arguments);
            |            };
            |        });
            |        var onRunComplete = this.onRunComplete;
            |        this.onRunComplete = function () {
            |            var result = onRunComplete.apply(this, arguments);
            |            require('fs').writeFileSync(countFile, String(reported));
            |            return result;
            |        };
            |    }
            |    LineReporter.${'$'}inject = KotlinReporter.${'$'}inject;
            |
            |    var registration = {};
            |    registration['reporter:' + replacement] = ['type', LineReporter];
            |    config.plugins = config.plugins || [];
            |    config.plugins.push(registration);
            |    config.reporters = reporters.map(function (name) { return name === original ? replacement : name; });
            |})();
        """.trimMargin()
    }
}

/**
 * Removes the previous run's [GenerateKarmaLineReporter.COUNT_FILE_NAME] before a wasm browser
 * test starts, so [VerifyKarmaResultCount] can only ever read the count of the run it follows.
 */
class ResetKarmaResultCount(private val countFile: File) : Action<Task> {
    override fun execute(task: Task) {
        countFile.delete()
    }
}

/**
 * Fails a wasm browser test task when Gradle recorded fewer results than Karma reported (#3605).
 *
 * The expected number comes from the producer, the Karma reporter, and the actual number from the
 * consumer, the `<testcase>` rows in the task's own JUnit XML. A `--tests` filter narrows both
 * the same way, so this needs no stand-down, unlike the cross-target `verifyTestResultParity`.
 * It runs only when the task succeeded: a failing test already fails the task.
 */
class VerifyKarmaResultCount(
    private val countFile: File,
    private val junitXmlDir: File,
) : Action<Task> {
    override fun execute(task: Task) {
        if (!countFile.isFile) {
            throw GradleException(
                "${task.path}: Karma left no result count at $countFile. The kuilt line reporter " +
                    "(GenerateKarmaLineReporter, #3605) did not run, so nothing guards this task " +
                    "against Gradle silently dropping results. Check that karma.conf.js still " +
                    "includes build/karma-config.d/line-reporter.js.",
            )
        }
        val reported = countFile.readText().trim().toInt()
        val testcase = Regex("<testcase\\s")
        val recorded = junitXmlDir.walkTopDown()
            .filter { it.isFile && it.name.startsWith("TEST-") && it.extension == "xml" }
            .sumOf { file -> testcase.findAll(file.readText()).count() }
        if (recorded < reported) {
            throw GradleException(
                "${task.path}: Karma reported $reported result(s) but Gradle recorded only " +
                    "$recorded. The missing ${reported - recorded} were dropped between the browser " +
                    "and the test report, and the task would otherwise have passed. The known cause " +
                    "is KGP's 1 MB service-message limit (#3605, #2185): look in this task's log for " +
                    "'too long teamcity service message'.",
            )
        }
        task.logger.info("${task.path}: Karma reported $reported result(s); Gradle recorded $recorded.")
    }
}
