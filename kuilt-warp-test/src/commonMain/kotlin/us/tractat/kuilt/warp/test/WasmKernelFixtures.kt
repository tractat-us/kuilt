 * that validation in *this object's* initializer: measured, a fixture drifted back into the
 * high-bit region reddened 19 of 20 conformance tests as `ExceptionInInitializerError` /
 * `NoClassDefFoundError`, with the sentence naming the violated relation buried in exactly one of
 * them. Lazily, the same drift reds only the properties that use the vector, and reds them with
 * the message.
 */
